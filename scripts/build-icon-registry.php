<?php

/**
 * Generates resources/views/components/ui/icon.blade.php — our own inline SVG
 * icon registry, built from the MIT-licensed Heroicons artwork that ships inside
 * the starter kit's published icon stubs. Re-run after adding an icon name.
 *
 * Usage: php scripts/build-icon-registry.php
 */
$source = __DIR__.'/../vendor/livewire/flux/stubs/resources/views/flux/icon';
$target = __DIR__.'/../resources/views/components/ui/icon.blade.php';

$icons = [
    // Kit UI (names carried over so data-test hooks and existing views survive).
    'arrow-path', 'arrow-right-start-on-rectangle', 'arrow-left', 'bars-2', 'check',
    'check-circle', 'chevron-down', 'chevron-right', 'chevron-up', 'cog', 'computer-desktop',
    'document-duplicate', 'envelope', 'exclamation-triangle', 'eye', 'eye-slash', 'finger-print',
    'home', 'information-circle', 'key', 'loading', 'lock-closed', 'magnifying-glass', 'moon',
    'pencil', 'plus', 'qr-code', 'sun', 'trash', 'x-circle', 'x-mark', 'arrow-down-tray',
    'bell-alert', 'bell', 'circle-stack', 'clipboard-document-list', 'queue-list',
    'chevron-left', 'arrow-right-end-on-rectangle',

    // Module navigation.
    'truck', 'cube', 'map', 'wrench', 'receipt-percent', 'calculator', 'users', 'user-circle',
    'globe-alt', 'chart-bar', 'shield-check', 'document-text', 'folder', 'banknotes', 'scale',
    'clock', 'signal', 'building-storefront', 'identification', 'hashtag',
];

$entries = [];
$missing = [];

foreach ($icons as $name) {
    $file = "{$source}/{$name}.blade.php";

    if (! is_file($file)) {
        $missing[] = $name;

        continue;
    }

    $contents = file_get_contents($file);

    // The outline variant is the first <svg> block in the stub. Attribute values
    // in that block contain "->" (Blade's $attributes->class(...)), so the tag
    // cannot be split on ">" — pull the pieces we need out instead.
    if (! preg_match('#<svg\b(?P<block>.*?)</svg>#s', $contents, $m)) {
        $missing[] = "{$name} (no svg)";

        continue;
    }

    $block = $m['block'];

    // First block in every stub is the outline variant; detect fill style from it.
    $solid = (bool) preg_match('#<svg[^>]*fill="currentColor"#s', '<svg'.$block);

    preg_match('#viewBox="([^"]+)"#', $block, $vb);

    // Only <path> elements carry the artwork; Blade expressions live in the tag itself.
    preg_match_all('#<path\b[^>]*/?>#', $block, $paths);

    if ($paths === [] || empty($paths[0])) {
        $missing[] = "{$name} (no paths)";

        continue;
    }

    $joined = preg_replace('/\s+/', ' ', implode(' ', $paths[0]));
    $literal = str_replace(['\\', "'"], ['\\\\', "\\'"], $joined);

    $entries[] = sprintf(
        "        '%s' => [\n            'viewBox' => '%s',\n            'solid' => %s,\n            'paths' => '%s',\n        ],",
        $name,
        $vb[1] ?? '0 0 24 24',
        $solid ? 'true' : 'false',
        $literal
    );
}

$lookup = implode("\n", $entries);

$blade = <<<'BLADE'
{{--
    Generated by scripts/build-icon-registry.php — do not hand-edit.
    Icon artwork: Heroicons (MIT), https://heroicons.com
--}}
@props([
    'name',
    'size' => '4',
])

@php
    $registry = [
BLADE;

$blade .= "\n{$lookup}\n    ];\n";

$blade .= <<<'BLADE'

    // Literal class names so the Tailwind v4 scanner sees them (dynamic
    // "size-{$size}" alone would never be generated).
    $sizes = ['3' => 'size-3', '4' => 'size-4', '5' => 'size-5', '6' => 'size-6', '8' => 'size-8'];
    $sizeClass = $sizes[$size] ?? $sizes['4'];

    $icon = $registry[$name] ?? throw new InvalidArgumentException(
        "Unknown ui-icon [{$name}]. Add it to scripts/build-icon-registry.php and re-run."
    );
@endphp

<svg
    xmlns="http://www.w3.org/2000/svg"
    viewBox="{{ $icon['viewBox'] }}"
    class="shrink-0 {{ $sizeClass }} {{ $attributes->get('class') }}"
    @if($icon['solid'])
        fill="currentColor"
    @else
        fill="none" stroke-width="1.5" stroke="currentColor"
    @endif
    aria-hidden="true"
    {{ $attributes->except('class') }}
>{!! $icon['paths'] !!}</svg>
BLADE;

if (! is_dir($dir = dirname($target))) {
    mkdir($dir, 0o755, true);
}

file_put_contents($target, $blade.PHP_EOL);

fwrite(STDERR, sprintf(
    'Wrote %s with %d icons%s'.PHP_EOL,
    basename($target),
    count($entries),
    $missing === [] ? '' : ' — MISSING: '.implode(', ', $missing)
));
